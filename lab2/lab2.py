# Задание 1
# Программа находит среднее арифметическое трёх целых чисел

# Ввод трёх целых чисел
a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))
c = int(input("Введите третье число: "))

# Вычисление среднего арифметического
average = (a + b + c) / 3

# Вывод результата
print("Среднее арифметическое:", average)

# Задание 2
# Программа проверяет, делится ли число на 3 и на 5 одновременно

# Ввод целого числа
x = int(input("Введите целое число: "))

# Проверка делимости на 3 и 5 одновременно
if x % 3 == 0 and x % 5 == 0:
    # Если число делится и на 3, и на 5
    print("Число делится на 3 и на 5 одновременно")
else:
    # Во всех остальных случаях
    print("Число НЕ делится на 3 и на 5 одновременно")

# Задание 3
# Программа вычисляет произведение чисел от 1 до n

# Ввод натурального числа
n = int(input("Введите натуральное число n: "))

# Начальное значение произведения
product = 1

# Цикл для вычисления произведения
for i in range(1, n + 1):
    product *= i

# Вывод результата
print("Произведение чисел от 1 до", n, "равно", product)

# Задание 4
# Программа выводит все чётные числа от 1 до n и считает их количество

# Ввод натурального числа
n = int(input("Введите натуральное число n: "))

# Счётчик чётных чисел
count = 0

print("Чётные числа от 1 до", n, ":")

# Цикл перебора чисел от 1 до n
for i in range(1, n + 1):
    # Проверка, является ли число чётным
    if i % 2 == 0:
        print(i)
        count += 1  # Увеличиваем счётчик

# Вывод количества чётных чисел
print("Количество чётных чисел:", count)